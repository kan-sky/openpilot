def digest(path):
  value = hashlib.sha256()
  with Path(path).open('rb') as stream:
    for chunk in iter(lambda: stream.read(4 << 20), b''):
      value.update(chunk)
  return value.hexdigest()


def identity(value):
  return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def sha(value):
  if not isinstance(value, str) or re.fullmatch('[a-f0-9]{64}', value) is None:
    raise ValueError('Expected a complete SHA256')
  return value


def regular(path):
  path = Path(path)
  if path.is_symlink() or not path.is_file():
    raise ValueError('Expected a regular file: ' + str(path))
  return path


def read_json(path):
  path = regular(path)
  if path.stat().st_size > 1 << 20:
    raise ValueError('Oversized JSON')
  value = json.loads(path.read_text())
  if not isinstance(value, dict):
    raise ValueError('Expected a JSON object')
  return value


def sync_dir(path):
  fd = os.open(path, os.O_RDONLY | os.O_DIRECTORY)
  try:
    os.fsync(fd)
  finally:
    os.close(fd)


def atomic_bytes(path, data, mode=0o644):
  path = Path(path)
  temporary = path.with_name('.' + path.name + '.' + uuid.uuid4().hex)
  try:
    with temporary.open('xb') as stream:
      stream.write(data)
      stream.flush()
      os.fsync(stream.fileno())
    temporary.chmod(mode)
    os.replace(temporary, path)
    sync_dir(path.parent)
  finally:
    temporary.unlink(missing_ok=True)


def atomic_json(path, value):
  atomic_bytes(path, (json.dumps(value, sort_keys=True, indent=2) + '\n').encode())


def allowed(name):
  path = Path(name)
  if path.is_absolute() or '..' in path.parts or str(path) != name:
    return False
  return (name in {SPEC, SELF, SERVER, 'third_party/jetlink/LICENSE'} or
          (name.startswith('third_party/jetlink/jetlink/') and path.suffix == '.py'
           and not any(p in ('tests', '__pycache__') for p in path.parts)))


def tree_hash(root, exclude=()):
  """Include unchanged base files and symlink targets, not generated bytecode."""
  root = Path(root)
  files = {}
  for path in sorted(root.rglob('*')):
    name = path.relative_to(root).as_posix()
    if name in exclude or '__pycache__' in path.parts or path.suffix == '.pyc':
      continue
    if path.is_symlink():
      files[name] = {'link': os.readlink(path)}
    elif path.is_file():
      files[name] = {'sha256': digest(path)}
    elif not path.is_dir():
      raise ValueError('Unsupported base entry: ' + name)
  return identity(files)


def source_identity(root):
  root = Path(root).resolve()
  git = ['git', '-C', str(root)]
  revision = subprocess.check_output([*git, 'rev-parse', 'HEAD'], text=True).strip()
  names = subprocess.check_output([*git, 'ls-files', '-z', '--', 'third_party/jetlink'], text=True).split('\0')
  names = {name for name in names if allowed(name)} | {SPEC, SELF, SERVER}
  if not REQUIRED <= names:
    raise ValueError('Required N16 runtime files must be tracked before packaging')
  files = {name: digest(regular(root / name)) for name in sorted(names)}
  if files[SPEC] != SPEC_SHA256:
    raise ValueError('N16 spec differs from the reviewed full contract')
  return {'source_revision': revision, 'files': files, 'content_sha256': identity(files)}


def prepare(root, output, expected_revision, expected_content):
  root, output = Path(root).resolve(), Path(output)
  before = source_identity(root)
  if before['source_revision'] != expected_revision or before['content_sha256'] != sha(expected_content):
    raise ValueError('Source revision/content changed; review identity before packaging')
  manifest = dict(before, format=1, kind='device-local-n16', base_source_commit=BASE, model=MODEL)
  with output.open('xb') as stream:
    with tarfile.open(fileobj=stream, mode='w:gz') as archive:
      for name in [*before['files'], MANIFEST]:
        data = json.dumps(manifest, sort_keys=True).encode() if name == MANIFEST else regular(root / name).read_bytes()
        if name != MANIFEST and hashlib.sha256(data).hexdigest() != before['files'][name]:
          raise ValueError('Source changed during packaging')
        entry = tarfile.TarInfo(name)
        entry.size, entry.mode = len(data), 0o644
        archive.addfile(entry, io.BytesIO(data))
    stream.flush()
    os.fsync(stream.fileno())
  if source_identity(root) != before:
    raise ValueError('Source changed during packaging; discard this bundle')
  return dict(manifest, bundle_sha256=digest(output))


def validate_manifest(value):
  if (value.get('format') != 1 or value.get('kind') != 'device-local-n16'
      or value.get('base_source_commit') != BASE or value.get('model') != MODEL
      or re.fullmatch('[a-f0-9]{40}', str(value.get('source_revision'))) is None):
    raise ValueError('Wrong overlay identity')
  files = value.get('files')
  if not isinstance(files, dict) or not REQUIRED <= files.keys() or len(files) > 512:
    raise ValueError('Incomplete overlay file manifest')
  if any(not allowed(name) or sha(value) != value for name, value in files.items()):
    raise ValueError('Disallowed overlay path')
  if files[SPEC] != SPEC_SHA256 or identity(files) != value.get('content_sha256'):
    raise ValueError('Overlay content identity mismatch')
  return value


def extract(bundle, destination, expected_sha256):
  if regular(bundle).stat().st_size > MAX_BUNDLE or digest(bundle) != sha(expected_sha256):
    raise ValueError('Bundle checksum/size mismatch')
  with tarfile.open(bundle, 'r:gz') as archive:
    members = archive.getmembers()
    names = [member.name for member in members]
    if (len(names) > 513 or len(names) != len(set(names)) or
        sum(member.size for member in members) > MAX_EXPANDED or any(m.size < 0 for m in members) or
        any(not m.isfile() or (m.name != MANIFEST and not allowed(m.name)) for m in members)):
      raise ValueError('Unsafe or oversized bundle')
    if MANIFEST not in names:
      raise ValueError('Missing overlay manifest')
    if archive.getmember(MANIFEST).size > 1 << 20:
      raise ValueError('Oversized overlay manifest')
    manifest = validate_manifest(json.load(archive.extractfile(MANIFEST)))
    if set(names) != set(manifest['files']) | {MANIFEST}:
      raise ValueError('Archive and file manifest differ')
    for member in members:
      data = archive.extractfile(member).read()
      if member.name != MANIFEST and hashlib.sha256(data).hexdigest() != manifest['files'][member.name]:
        raise ValueError('Overlay file checksum mismatch: ' + member.name)
      path = destination / member.name
      path.parent.mkdir(parents=True, exist_ok=True, mode=0o755)
      atomic_bytes(path, data)
  return manifest


def spec_at(root):
  path = regular(Path(root) / SPEC)
  if digest(path) != SPEC_SHA256:
    raise ValueError('N16 full spec checksum mismatch')
  return read_json(path)


def check_cache(model, plan, meta, spec, plan_sha256, meta_sha256):
  for path, length, expected in ((model, MODEL_BYTES, MODEL), (plan, PLAN_BYTES, sha(plan_sha256))):
    if regular(path).stat().st_size != length or digest(path) != expected:
      raise ValueError('Cache artifact checksum/size mismatch: ' + str(path))
  if digest(regular(meta)) != sha(meta_sha256):
    raise ValueError('Cache metadata checksum mismatch')
  facts = read_json(meta)
  if (facts.get('backend') != 'trt' or facts.get('trt_version') != '10.3.0'
      or facts.get('device') != 'Orin-sm87' or facts.get('spec') != spec):
    raise ValueError('Cache metadata runtime/full spec mismatch')
  # Native builder sidecars have spec.sha256, not a source_sha256 member.
  if 'source_sha256' in facts and facts['source_sha256'] != MODEL:
    raise ValueError('Conflicting cache source identity')


def cache_paths(runtime):
  cache = Path(runtime) / 'cache'
  stem = MODEL[:16] + '.' + TAG
  return cache / 'models' / (MODEL[:16] + '.onnx'), cache / 'engines' / (stem + '.plan'), cache / 'engines' / (stem + '.json')


def copy_cache(sources, runtime, owner):
  targets = cache_paths(runtime)
  for source, target in zip(sources, targets, strict=True):
    if target.parent.is_symlink() or not target.parent.is_dir():
      raise ValueError('Unsafe/unprepared cache directory')
    expected = digest(source)
    if target.exists() or target.is_symlink():
      if digest(regular(target)) != expected:
        raise ValueError('Existing N16 cache differs; refusing to overwrite it')
      continue
    temporary = target.with_name('.n16-' + uuid.uuid4().hex)
    try:
      with regular(source).open('rb') as src, temporary.open('xb') as dst:
        shutil.copyfileobj(src, dst, 4 << 20)
        dst.flush()
        os.fsync(dst.fileno())
      if digest(temporary) != expected:
        raise ValueError('Cache copy checksum mismatch')
      temporary.chmod(0o644)
      os.chown(temporary, *owner)
      os.replace(temporary, target)
      sync_dir(target.parent)
    finally:
      temporary.unlink(missing_ok=True)
  return targets


def platform_check():
  if platform.machine() != 'aarch64':
    raise ValueError('N16 cache requires aarch64 Orin NX 8GB')
  compatible = Path('/proc/device-tree/compatible').read_bytes().decode().split('\0')
  if not any(re.fullmatch(r'nvidia,p3767-0001(?:\+[^\x00]+)?', item) for item in compatible):
    raise ValueError('Expected Orin NX 8GB module identity nvidia,p3767-0001')


def native_backend():
  from jetlink.server.backends.trt import TrtBackend
  backend = TrtBackend()
  if backend.runtime_version != '10.3.0' or backend.describe()['device'] != 'Orin-sm87' or backend.tag() != TAG:
    raise ValueError('Installed TensorRT/device does not match the prepared plan')
  return backend


def verify_files(root):
  root = Path(root).resolve()
  value = validate_manifest(read_json(root / MANIFEST))
  if regular(root / 'SOURCE_COMMIT').read_text().strip() != BASE:
    raise ValueError('Overlay no longer belongs to the selected signed base')
  for name, expected in value['files'].items():
    path = root / name
    if not path.resolve().is_relative_to(root) or digest(regular(path)) != expected:
      raise ValueError('Installed overlay file changed: ' + name)
  for path in (root, root / MANIFEST, *(root / name for name in value['files'])):
    stat = path.stat()
    if stat.st_uid != RELEASE_UID or stat.st_mode & 0o022:
      raise ValueError('Overlay must be root-owned and not group/world writable')
  if tree_hash(root, (MANIFEST,)) != value.get('runtime_tree_sha256'):
    raise ValueError('Installed base/overlay tree changed')
  return value


def verify_runtime(root):
  """Read-only startup capability check; absent overlays stay completely alone."""
  root = Path(root).resolve()
  if not (root / MANIFEST).exists():
    return None
  runtime = root.parent.parent
  if (runtime / TRANSACTION).exists():
    raise ValueError('Interrupted N16 transaction: run n16_overlay.py recover')
  if root.parent != runtime / 'releases' or (runtime / 'current').resolve() != root:
    raise ValueError('N16 runtime is not the selected release')
  value = verify_files(root)
  platform_check()
  sys.path.insert(0, str(root / 'third_party/jetlink'))
  native_backend()
  check_cache(*cache_paths(runtime), spec_at(root), value['plan_sha256'], value['meta_sha256'])
  selected = read_json(runtime / 'cache/last-loaded.json')
  if selected != {'sha256': MODEL, 'frame_skip': 4, 'backend': 'trt'}:
    raise ValueError('N16 cached model selection changed')
  return {key: value[key] for key in ('model', 'content_sha256', 'base_source_commit')}


def run_child(command, timeout):
  if not 0 < timeout <= MAX_PROBE_SECONDS:
    raise ValueError('Invalid child timeout')
  process = subprocess.Popen(command, start_new_session=True, cwd='/tmp')
  try:
    code = process.wait(timeout=timeout)
    if code:
      raise subprocess.CalledProcessError(code, command)
  except BaseException:
    try:
      os.killpg(process.pid, signal.SIGKILL)
    except ProcessLookupError:
      pass
    process.wait(timeout=10)
    raise


def native_probe(root, runtime):
  """Direct cached load only: no EngineHost request/build/remember side effects."""
  root, runtime = Path(root).resolve(), Path(runtime).resolve()
  value = verify_files(root)
  check_cache(*cache_paths(runtime), spec_at(root), value['plan_sha256'], value['meta_sha256'])
  platform_check()
  sys.path[:0] = [str(root / 'third_party/jetlink'), str(root / 'tools/jetlink')]
  import server  # noqa: F401 -- startup verification belongs inside server.__main__
  import numpy as np
  from jetlink.spec import ModelSpec
  from jetlink.server.cache import EngineCache
  from jetlink.server.session import EngineHost
  backend = native_backend()
  cache = EngineCache(runtime / 'cache', backend)
  engine = backend.load(cache.entry(MODEL).path)
  try:
    loaded = EngineHost(cache)._warm(engine, ModelSpec.from_dict(spec_at(root)))
    first = None
    for index in range(4):
      if index == 3:
        loaded.queues.reset()
      loaded.queues.step_into(np.zeros(loaded.spec.warped_shape, np.uint8),
                             np.zeros(loaded.spec.packed_nelem, np.float32), loaded.host_inputs)
      outputs = engine.run()
      loaded.queues.feedback(outputs)
      if not outputs or not all(np.isfinite(v).all() for v in outputs.values()):
        raise ValueError('Nonfinite N16 cached inference')
      if first is None:
        first = outputs['outputs'].copy()
      elif index == 3 and not np.array_equal(first, outputs['outputs']):
        raise ValueError('N16 cached recurrent reset mismatch')
    print('N16_CACHED_PROBE_OK', MODEL, flush=True)
  finally:
    engine.close()


def selected(runtime):
  runtime = Path(runtime).resolve()
  if not (runtime / 'current').is_symlink():
    raise ValueError('Current must be a release symlink')
  target = (runtime / 'current').resolve(strict=True)
  if target.parent != runtime / 'releases' or not target.is_dir():
    raise ValueError('Current points outside releases')
  return target


def service(action, names):
  if names:
    subprocess.run(['systemctl', action, *names], check=True, timeout=45)


def active_services():
  return [name for name in SERVICES if subprocess.run(
    ['systemctl', 'is-active', '--quiet', name], timeout=10).returncode == 0]


def resume(names):
  service('start', list(reversed(names)))
  service('is-active', names)


def snapshot(runtime):
  current = selected(runtime)
  return {'selected': current.name, 'tree_sha256': tree_hash(current),
          'last_loaded': base64.b64encode(regular(runtime / 'cache/last-loaded.json').read_bytes()).decode(),
          'services': active_services()}


def switch(runtime, target):
  temporary = runtime / ('current.n16-' + uuid.uuid4().hex)
  try:
    temporary.symlink_to('releases/' + target.name)
    os.replace(temporary, runtime / 'current')
    sync_dir(runtime)
  finally:
    temporary.unlink(missing_ok=True)


def restore(runtime, record):
  name = record['selected']
  if not isinstance(name, str) or Path(name).name != name or name in ('.', '..'):
    raise ValueError('Unsafe recovery release')
  target = runtime / 'releases' / name
  if target.is_symlink() or not target.is_dir() or tree_hash(target) != record['tree_sha256']:
    raise ValueError('Recovery release changed')
  if not set(record['services']) <= set(SERVICES):
    raise ValueError('Unsafe recovery services')
  remembered = base64.b64decode(record['last_loaded'], validate=True)
  service('stop', SERVICES)
  atomic_bytes(runtime / 'cache/last-loaded.json', remembered)
  switch(runtime, target)
  resume(record['services'])


def recover(runtime):
  transaction = runtime / TRANSACTION
  record = read_json(transaction)
  if selected(runtime).name not in record['allowed_current']:
    raise ValueError('Another release superseded this transaction; refusing recovery')
  restore(runtime, record['restore'])
  transaction.unlink()
  sync_dir(runtime)


@contextmanager
def locked_runtime(runtime):
  import fcntl
  if os.geteuid() != 0:
    raise PermissionError('Root installation is required')
  if (not Path('/etc/carrot-jetlink-image.json').is_file()
      or not Path('/etc/carrot-jetlink-protected.json').is_file()
      or read_json(Path('/run/carrot-storage.json')).get('state') != 'protected'):
    raise ValueError('Protected DATA must be mounted; never modify factory recovery')
  platform_check()
  with Path('/run/carrot-jetlink-update.lock').open('a') as lock:
    fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    if (runtime / 'updates/transaction.json').exists() or (runtime / 'updates/pending.json').exists():
      raise ValueError('Resolve the pending signed update before N16 maintenance')
    yield


def install(runtime, bundle, bundle_sha256, sources, plan_sha256, meta_sha256,
            expected_current, expected_tree, probe=None):
  """Caller holds locked_runtime; callbacks only make filesystem tests portable."""
  runtime = Path(runtime).resolve()
  current = selected(runtime)
  if (current.name != expected_current or tree_hash(current) != sha(expected_tree)
      or regular(current / 'SOURCE_COMMIT').read_text().strip() != BASE
      or (current / MANIFEST).exists()):
    raise ValueError('Expected exact unoverlaid base/current tree')
  if (runtime / TRANSACTION).exists():
    raise ValueError('Recover the interrupted N16 transaction first')
  before = snapshot(runtime)
  with tempfile.TemporaryDirectory(prefix='.n16-stage-', dir=runtime / 'releases') as temporary:
    staging = Path(temporary)
    overlay = staging / 'overlay'
    overlay.mkdir()
    manifest = extract(Path(bundle), overlay, bundle_sha256)
    check_cache(*sources, spec_at(overlay), plan_sha256, meta_sha256)
    if shutil.disk_usage(runtime).free < MODEL_BYTES + PLAN_BYTES + (256 << 20):
      raise ValueError('Insufficient space for copied cache and rollback release')
    candidate = staging / 'runtime'
    shutil.copytree(current, candidate, symlinks=True, ignore=shutil.ignore_patterns('__pycache__', '*.pyc'))
    for name in manifest['files']:
      target = candidate / name
      if target.is_symlink() or not target.resolve().is_relative_to(candidate):
        raise ValueError('Overlay destination redirects outside release')
      target.parent.mkdir(parents=True, exist_ok=True, mode=0o755)
      atomic_bytes(target, (overlay / name).read_bytes())
    manifest.update(base_tree_sha256=expected_tree, plan_sha256=sha(plan_sha256), meta_sha256=sha(meta_sha256),
                    runtime_tree_sha256=tree_hash(candidate, (MANIFEST,)))
    atomic_json(candidate / MANIFEST, manifest)
    for directory in (staging, candidate, *(p for p in candidate.rglob('*') if p.is_dir() and not p.is_symlink())):
      directory.chmod(0o755)
    for path in candidate.rglob('*'):
      if path.is_file() and not path.is_symlink():
        path.chmod(path.stat().st_mode & 0o755)
    target = runtime / 'releases' / ('hl-n16-' + manifest['content_sha256'][:20] + '-' + uuid.uuid4().hex[:12])
    journal = {'format': 1, 'restore': before, 'allowed_current': [current.name, target.name]}
    atomic_json(runtime / TRANSACTION, journal)
    try:
      service('stop', SERVICES)
      import pwd
      account = pwd.getpwnam('jetlink')
      copy_cache(sources, runtime, (account.pw_uid, account.pw_gid))
      if probe is None:
        run_child(['runuser', '-u', 'jetlink', '--', str(runtime / 'venv/bin/python'), '-B',
                   str(candidate / SELF), 'probe', '--root', str(candidate), '--runtime', str(runtime)], MAX_PROBE_SECONDS)
      else:
        probe(candidate, runtime)
      verify_files(candidate)
      check_cache(*cache_paths(runtime), spec_at(candidate), plan_sha256, meta_sha256)
      if selected(runtime) != current or tree_hash(current) != expected_tree:
        raise ValueError('Current changed during installation')
      # Persist every cloned base file as well as our overlay before selection.
      for path in candidate.rglob('*'):
        if path.is_file() and not path.is_symlink():
          with path.open('rb') as stream:
            os.fsync(stream.fileno())
      for path in sorted((p for p in candidate.rglob('*') if p.is_dir() and not p.is_symlink()), reverse=True):
        sync_dir(path)
      sync_dir(candidate)
      candidate.rename(target)
      sync_dir(runtime / 'releases')
      atomic_json(runtime / PREVIOUS, {'installed': target.name, 'restore': before})
      atomic_json(runtime / 'cache/last-loaded.json', {'sha256': MODEL, 'frame_skip': 4, 'backend': 'trt'})
      switch(runtime, target)
      # Startup verification requires no pending transaction. Do not start the
      # candidate until the durable commit, then roll back a failed start below.
      (runtime / TRANSACTION).unlink()
      sync_dir(runtime)
      resume(before['services'])
    except BaseException:
      if not (runtime / TRANSACTION).exists():
        atomic_json(runtime / TRANSACTION, journal)
      recover(runtime)
      raise
  return {key: manifest[key] for key in ('model', 'content_sha256', 'base_source_commit')}


def rollback(runtime, expected_current, expected_tree):
  runtime = Path(runtime).resolve()
  if (runtime / TRANSACTION).exists():
    raise ValueError('Recover the interrupted N16 transaction first')
  current = selected(runtime)
  record = read_json(runtime / PREVIOUS)
  if (current.name != expected_current or current.name != record['installed']
      or tree_hash(current) != sha(expected_tree) or regular(current / 'SOURCE_COMMIT').read_text().strip() != BASE):
    raise ValueError('Another release superseded the overlay; refusing rollback')
  atomic_json(runtime / TRANSACTION, {'format': 1, 'restore': record['restore'],
                                    'allowed_current': [current.name, record['restore']['selected']]})
  recover(runtime)


def main():
  parser = argparse.ArgumentParser(description=__doc__)
  sub = parser.add_subparsers(dest='action', required=True)
  inspect = sub.add_parser('identity')
  inspect.add_argument('--root', type=Path, required=True)
  fingerprint = sub.add_parser('tree-hash', help='Read-only current-release tree fingerprint for install/rollback')
  fingerprint.add_argument('--root', type=Path, required=True)
  build = sub.add_parser('prepare')
  build.add_argument('--root', type=Path, required=True)
  build.add_argument('--output', type=Path, required=True)
  build.add_argument('--expect-source-revision', required=True)
  build.add_argument('--expect-content-sha256', required=True)
  for action in ('verify', 'probe'):
    child = sub.add_parser(action)
    child.add_argument('--root', type=Path, required=True)
    if action == 'probe':
      child.add_argument('--runtime', type=Path, default=RUNTIME)
  for action in ('install', 'rollback', 'recover'):
    command = sub.add_parser(action)
    command.add_argument('--confirm-offroad', action='store_true')
    if action != 'recover':
      command.add_argument('--expect-current', required=True, help='Exact release directory basename')
      command.add_argument('--expect-current-tree-sha256', required=True)
    if action == 'install':
      for flag in ('bundle', 'model', 'plan', 'meta'):
        command.add_argument('--' + flag, type=Path, required=True)
      for flag in ('bundle-sha256', 'plan-sha256', 'meta-sha256'):
        command.add_argument('--' + flag, required=True)
  args = parser.parse_args()
  if args.action == 'identity':
    result = source_identity(args.root)
  elif args.action == 'tree-hash':
    result = {'root': str(args.root.resolve()), 'tree_sha256': tree_hash(args.root)}
  elif args.action == 'prepare':
    result = prepare(args.root, args.output, args.expect_source_revision, args.expect_content_sha256)
  elif args.action == 'verify':
    result = verify_runtime(args.root)
  elif args.action == 'probe':
    native_probe(args.root, args.runtime)
    return
  else:
    if not args.confirm_offroad:
      parser.error('Keep ignition off/devices on desk, then use --confirm-offroad')
    with locked_runtime(RUNTIME):
      if args.action == 'recover':
        result = recover(RUNTIME)
      elif args.action == 'rollback':
        result = rollback(RUNTIME, args.expect_current, args.expect_current_tree_sha256)
      else:
        result = install(RUNTIME, args.bundle, args.bundle_sha256, (args.model, args.plan, args.meta),
                         args.plan_sha256, args.meta_sha256, args.expect_current, args.expect_current_tree_sha256)
  print(json.dumps(result, sort_keys=True))


